// Finds what DynamiteExportOld.java recorded in 1.0.15.3 exe in 1.0.15.4 exe. Run it on 1.0.15.4 mgsvtpp.exe after
// running DynamiteExportOld.java on 1.0.15.3 exe. Functions are matched by name, so names must be transferred to
// the new exe first (Version Tracking or by hand).
// Asks for dynamite's hook/src folder, reads dynamite_1_0_15_3.tsv from it, rewrites mgsvtpp_addresses_1_0_15_4_en.h
// and writes dynamite_patches_1_0_15_4.txt. Active entries of existing mgsvtpp_addresses_1_0_15_4_en.h are kept,
// so it is safe to run it again after filling in addresses by hand or naming more functions.
// Headless: analyzeHeadless ... -postScript DynamiteFindNew.java <path to hook/src>
//@category Dynamite

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import ghidra.program.model.listing.Instruction;
import ghidra.program.model.listing.InstructionIterator;
import ghidra.program.model.mem.Memory;
import ghidra.program.model.mem.MemoryBlock;
import ghidra.program.model.symbol.SourceType;

public class DynamiteFindNew extends GhidraScript {
    static final String IN = "dynamite_1_0_15_3.tsv";
    static final String ADDRESSES = "mgsvtpp_addresses_1_0_15_4_en.h";
    static final String REPORT = "dynamite_patches_1_0_15_4.txt";

    // function size may change a bit between versions, bigger difference needs a human
    static final double MIN_SIZE_RATIO = 0.75;
    static final double MAX_SIZE_RATIO = 1.33;

    static final Pattern ENTRY = Pattern.compile("\\{\\s*\"([^\"]+)\"\\s*,\\s*(0x[0-9a-fA-F]+)\\s*\\}");

    Map<String, List<Function>> functionsByName = new HashMap<>();

    @Override
    protected void run() throws Exception {
        File dir = getSrcDir();
        Map<String, Long> known = readKnown(new File(dir, ADDRESSES));
        indexFunctions();

        List<String> entries = new ArrayList<>();
        List<String> report = new ArrayList<>();
        int funcs = 0, funcsFound = 0, conflicts = 0, patches = 0, patchesFound = 0;

        for (String line : Files.readAllLines(new File(dir, IN).toPath(), StandardCharsets.UTF_8)) {
            String[] r = line.split("\t", -1);
            switch (r[0]) {
                case "break" -> entries.add("");
                case "func" -> {
                    funcs++;
                    String entry = findFunction(r, known);
                    if (!entry.trim().startsWith("//")) {
                        funcsFound++;
                        if (entry.contains("// CHECK")) {
                            conflicts++;
                        }
                    }
                    entries.add(entry);
                }
                case "patch" -> {
                    patches++;
                    if (findPatch(r, report)) {
                        patchesFound++;
                    }
                }
                case "string" -> {
                    patches++;
                    if (findString(r, report)) {
                        patchesFound++;
                    }
                }
                default -> throw new IllegalArgumentException("unexpected record in " + IN + ": " + line);
            }
        }

        writeAddresses(new File(dir, ADDRESSES), entries, funcsFound, funcs);

        List<String> header = new ArrayList<>();
        header.add(String.format("dynamite patches for 1.0.15.4, generated by DynamiteFindNew.java: %d of %d found",
            patchesFound, patches));
        header.add("FOUND: same function, same surrounding instructions and original bytes, check it in Ghidra anyway");
        header.add("");
        report.addAll(0, header);
        Files.write(new File(dir, REPORT).toPath(), report, StandardCharsets.UTF_8);

        println(String.format("functions: %d of %d found", funcsFound, funcs));
        if (conflicts > 0) {
            println(String.format("%d existing entries disagree with function names, see CHECK comments", conflicts));
        }
        println(String.format("patches: %d of %d found", patchesFound, patches));
        println("written " + new File(dir, ADDRESSES));
        println("written " + new File(dir, REPORT));
    }

    File getSrcDir() throws Exception {
        String[] args = getScriptArgs();
        File dir = args.length > 0 ? new File(args[0]) : askDirectory("Select dynamite hook/src folder", "Select");
        if (!new File(dir, IN).isFile()) {
            throw new IllegalArgumentException(
                dir + " must contain " + IN + ", run DynamiteExportOld.java on 1.0.15.3 exe first");
        }

        return dir;
    }

    // active entries of existing file, filled in by hand or by previous run
    static Map<String, Long> readKnown(File file) throws Exception {
        Map<String, Long> result = new LinkedHashMap<>();
        if (!file.isFile()) {
            return result;
        }

        for (String line : Files.readAllLines(file.toPath(), StandardCharsets.UTF_8)) {
            String t = line.trim();
            if (t.startsWith("//")) {
                continue;
            }

            Matcher m = ENTRY.matcher(t);
            if (m.find()) {
                result.put(m.group(1), parseHex(m.group(2)));
            }
        }

        return result;
    }

    // thunks are named after the function they jump to, they would make every name ambiguous
    void indexFunctions() {
        FunctionIterator it = currentProgram.getFunctionManager().getFunctions(true);
        while (it.hasNext()) {
            Function f = it.next();
            if (f.isThunk() || f.getSymbol().getSource() == SourceType.DEFAULT) {
                continue;
            }

            functionsByName.computeIfAbsent(f.getName(true), k -> new ArrayList<>()).add(f);
        }
    }

    // r: func, name, old address, full name, size, status
    String findFunction(String[] r, Map<String, Long> known) {
        String name = r[1];
        String oldAddress = r[2];
        String fullName = r[3];
        long oldSize = Long.parseLong(r[4]);
        String status = r[5];
        Long knownAddress = known.get(name);

        if (!status.equals("ok")) {
            if (knownAddress != null) {
                return active(name, knownAddress, "kept");
            }

            return missing(name, String.format("%s in 1.0.15.3 exe (%s), find by hand", status.toUpperCase(), oldAddress));
        }

        List<Function> candidates = functionsByName.getOrDefault(fullName, List.of());
        List<Long> addresses = new ArrayList<>();
        List<String> hexAddresses = new ArrayList<>();
        for (Function f : candidates) {
            addresses.add(f.getEntryPoint().getOffset());
            hexAddresses.add(hex(f.getEntryPoint().getOffset()));
        }

        // active entries were set by hand or accepted earlier, never replace them
        if (knownAddress != null) {
            if (addresses.isEmpty()) {
                return active(name, knownAddress, "kept, " + fullName + " not found by name");
            }

            if (addresses.contains(knownAddress)) {
                return active(name, knownAddress, fullName);
            }

            return active(name, knownAddress,
                String.format("CHECK %s is at %s", fullName, String.join(", ", hexAddresses)));
        }

        if (addresses.isEmpty()) {
            return missing(name, String.format("NOT FOUND %s (1.0.15.3: %s)", fullName, oldAddress));
        }

        if (addresses.size() > 1) {
            return missing(name, String.format("AMBIGUOUS %s at %s", fullName, String.join(", ", hexAddresses)));
        }

        Function f = candidates.get(0);
        long address = f.getEntryPoint().getOffset();
        long newSize = f.getBody().getNumAddresses();

        if (oldSize > 0) {
            double ratio = (double) newSize / oldSize;
            if (ratio < MIN_SIZE_RATIO || ratio > MAX_SIZE_RATIO) {
                return candidate(name, address, String.format("CHECK %s, size %d -> %d", fullName, oldSize, newSize));
            }
        }

        return active(name, address, fullName);
    }

    // r: patch, index, old address, function full name, offset, expected bytes, before, after, status, description
    boolean findPatch(String[] r, List<String> report) {
        String index = r[1];
        String oldAddress = r[2];
        String fullName = r[3];
        long oldOffset = parseHex(r[4]);
        byte[] expected = hexToBytes(r[5]);
        List<String> before = split(r[6]);
        List<String> after = split(r[7]);
        String status = r[8];
        String description = r[9];

        String result;
        boolean found = false;
        if (!status.equals("ok")) {
            result = String.format("%s in 1.0.15.3 exe, port by hand", status.toUpperCase());
        } else {
            List<Function> candidates = functionsByName.getOrDefault(fullName, List.of());
            if (candidates.size() != 1) {
                result = String.format("%s %s, port by hand", candidates.isEmpty() ? "NOT FOUND" : "AMBIGUOUS", fullName);
            } else {
                Function f = candidates.get(0);
                List<Instruction> instructions = instructions(f);
                List<Instruction> matches = matchPatch(instructions, expected, before, after);
                if (matches.isEmpty()) {
                    // compiler may change instructions before the patch, try without them
                    matches = matchPatch(instructions, expected, List.of(), after);
                }

                if (matches.size() == 1) {
                    Address a = matches.get(0).getAddress();
                    long offset = a.getOffset() - f.getEntryPoint().getOffset();
                    result = String.format("FOUND %s -> %s, %s +%s (was +%s)", oldAddress, hex(a.getOffset()),
                        fullName, hex(offset), hex(oldOffset));
                    found = true;
                } else if (matches.isEmpty()) {
                    result = String.format("NOT FOUND in %s at %s, port by hand", fullName,
                        hex(f.getEntryPoint().getOffset()));
                } else {
                    List<String> addresses = new ArrayList<>();
                    for (Instruction i : matches) {
                        addresses.add(hex(i.getAddress().getOffset()));
                    }
                    result = String.format("AMBIGUOUS in %s: %s, port by hand", fullName, String.join(", ", addresses));
                }
            }
        }

        report.add(String.format("#%s %s", index, result));
        report.add("    " + description + " (1.0.15.3: " + oldAddress + ")");
        return found;
    }

    List<Instruction> matchPatch(List<Instruction> instructions, byte[] expected, List<String> before,
                                 List<String> after) {
        List<Instruction> result = new ArrayList<>();
        for (int i = 0; i < instructions.size(); i++) {
            if (!mnemonicsMatch(instructions, i - before.size(), before)
                || !mnemonicsMatch(instructions, i, after)) {
                continue;
            }

            byte[] actual = readBytes(instructions.get(i).getAddress(), expected.length);
            if (Arrays.equals(actual, expected)) {
                result.add(instructions.get(i));
            }
        }

        return result;
    }

    static boolean mnemonicsMatch(List<Instruction> instructions, int from, List<String> mnemonics) {
        if (from < 0 || from + mnemonics.size() > instructions.size()) {
            return false;
        }

        for (int i = 0; i < mnemonics.size(); i++) {
            if (!instructions.get(from + i).getMnemonicString().equals(mnemonics.get(i))) {
                return false;
            }
        }

        return true;
    }

    // r: string, index, old address, string bytes, status, description
    boolean findString(String[] r, List<String> report) throws Exception {
        String index = r[1];
        String oldAddress = r[2];
        String status = r[4];
        String description = r[5];

        String result;
        boolean found = false;
        if (!status.equals("ok")) {
            result = String.format("%s in 1.0.15.3 exe, port by hand", status.toUpperCase());
        } else {
            List<String> addresses = new ArrayList<>();
            for (Address a : findAll(hexToBytes(r[3]))) {
                addresses.add(hex(a.getOffset()));
            }

            if (addresses.size() == 1) {
                result = String.format("FOUND %s -> %s, string", oldAddress, addresses.get(0));
                found = true;
            } else if (addresses.isEmpty()) {
                result = "NOT FOUND string, port by hand";
            } else {
                result = "AMBIGUOUS string at " + String.join(", ", addresses) + ", port by hand";
            }
        }

        report.add(String.format("#%s %s", index, result));
        report.add("    " + description + " (1.0.15.3: " + oldAddress + ")");
        return found;
    }

    List<Address> findAll(byte[] bytes) throws Exception {
        List<Address> result = new ArrayList<>();
        Memory memory = currentProgram.getMemory();
        for (MemoryBlock block : memory.getBlocks()) {
            if (!block.isInitialized()) {
                continue;
            }

            Address start = block.getStart();
            while (start != null && start.compareTo(block.getEnd()) <= 0) {
                Address a = memory.findBytes(start, block.getEnd(), bytes, null, true, monitor);
                if (a == null) {
                    break;
                }
                result.add(a);
                start = a.next();
            }
        }

        return result;
    }

    void writeAddresses(File file, List<String> entries, int found, int total) throws Exception {
        List<String> out = new ArrayList<>();
        out.add("#ifndef HOOK_DYNAMITE_MGSVTPP_ADDRESSES_1_0_15_4");
        out.add("#define HOOK_DYNAMITE_MGSVTPP_ADDRESSES_1_0_15_4");
        out.add("");
        out.add("#include <cstdint>");
        out.add("#include <map>");
        out.add("#include <string>");
        out.add("");
        out.add("// Addresses for game version 1.0.15.4 (June 9, 2026 update), not used yet.");
        out.add(String.format("// %d of %d addresses are known. Generated by hook/ghidra/DynamiteFindNew.java, see", found,
            total));
        out.add("// docs/PORTING.md; re-running it keeps active entries. Commented out entries need a human.");
        out.add("// Initial known entries came from IHHook 1.0.15.4 table (MIT, https://github.com/Phobos1641/mgs5-ihhook).");
        out.add("");
        out.add("namespace Dynamite {");
        out.add("    inline std::map<std::string, uint64_t> mgsvtpp_adresses_1_0_15_4_en{");
        out.addAll(entries);
        out.add("    };");
        out.add("}");
        out.add("");
        out.add("#endif");
        Files.write(file.toPath(), out, StandardCharsets.UTF_8);
    }

    static String active(String name, long address, String comment) {
        return String.format("        {\"%s\", %s}, // %s", name, hex(address), comment);
    }

    // found, but needs a human to confirm
    static String candidate(String name, long address, String comment) {
        return String.format("        // {\"%s\", %s}, // %s", name, hex(address), comment);
    }

    static String missing(String name, String comment) {
        return String.format("        // {\"%s\", 0x0}, // %s", name, comment);
    }

    List<Instruction> instructions(Function f) {
        List<Instruction> result = new ArrayList<>();
        InstructionIterator it = currentProgram.getListing().getInstructions(f.getBody(), true);
        while (it.hasNext()) {
            result.add(it.next());
        }

        return result;
    }

    byte[] readBytes(Address a, int len) {
        byte[] result = new byte[len];
        try {
            int n = currentProgram.getMemory().getBytes(a, result);
            return n == len ? result : null;
        } catch (Exception e) {
            return null;
        }
    }

    static List<String> split(String s) {
        return s.isEmpty() ? List.of() : Arrays.asList(s.split(","));
    }

    static long parseHex(String s) {
        return Long.parseUnsignedLong(s.substring(2), 16);
    }

    static String hex(long v) {
        return String.format("0x%x", v);
    }

    static byte[] hexToBytes(String s) {
        byte[] result = new byte[s.length() / 2];
        for (int i = 0; i < result.length; i++) {
            result[i] = (byte) Integer.parseInt(s.substring(i * 2, i * 2 + 2), 16);
        }

        return result;
    }
}
