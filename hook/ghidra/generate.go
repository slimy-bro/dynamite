package main

import (
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"strings"
)

// DynamitePort.java must work without dynamite sources, so it carries a copy of them

const (
	begin = "    // BEGIN GENERATED by generate.go from hook/src, do not edit\n"
	end   = "    // END GENERATED\n"
)

var embedded = []struct {
	Name string
	File string
}{
	{Name: "ADDRESSES_1_0_15_3", File: "mgsvtpp_addresses_1_0_15_3_en.h"},
	{Name: "PATCHES_1_0_15_3", File: "dynamitePatches.cpp"},
	{Name: "ADDRESSES_1_0_15_4", File: "mgsvtpp_addresses_1_0_15_4_en.h"},
}

// textBlock turns file contents into Java text block
func textBlock(s string) string {
	s = strings.ReplaceAll(s, "\r", "")
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"""`, `\"""`)
	return `"""` + "\n" + strings.TrimRight(s, "\n") + "\n" + `"""`
}

// Render returns java with generated section replaced by files from srcDir
func Render(srcDir string, java string) (string, error) {
	start := strings.Index(java, begin)
	stop := strings.Index(java, end)
	if start < 0 || stop < start {
		return "", fmt.Errorf("generated section markers not found")
	}

	var sb strings.Builder
	sb.WriteString(java[:start])
	sb.WriteString(begin)
	for i, e := range embedded {
		data, err := os.ReadFile(filepath.Join(srcDir, e.File))
		if err != nil {
			return "", err
		}

		if i > 0 {
			sb.WriteString("\n")
		}
		sb.WriteString(fmt.Sprintf("    // %s\n", e.File))
		sb.WriteString(fmt.Sprintf("    static final String %s = %s;\n", e.Name, textBlock(string(data))))
	}
	sb.WriteString(java[stop:])

	return sb.String(), nil
}

func main() {
	srcDir := filepath.Join("hook", "src")
	javaPath := filepath.Join("hook", "ghidra", "DynamitePort.java")

	java, err := os.ReadFile(javaPath)
	if err != nil {
		slog.Error("read", "error", err.Error())
		os.Exit(1)
	}

	out, err := Render(srcDir, string(java))
	if err != nil {
		slog.Error("render", "error", err.Error())
		os.Exit(1)
	}

	if err = os.WriteFile(javaPath, []byte(out), 0644); err != nil {
		slog.Error("write", "error", err.Error())
		os.Exit(1)
	}

	slog.Info("generated", "name", javaPath)
}
